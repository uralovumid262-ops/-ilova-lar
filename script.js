// ===== Theme Management =====
function toggleTheme() {
    const html = document.documentElement;
    const currentTheme = html.getAttribute('data-theme');
    const newTheme = currentTheme === 'dark' ? 'light' : 'dark';
    html.setAttribute('data-theme', newTheme);
    
    // Update theme icon
    const themeIcon = document.getElementById('theme-icon');
    if (themeIcon) {
        themeIcon.textContent = newTheme === 'dark' ? '☀️' : '🌙';
    }
    
    // Save theme preference
    localStorage.setItem('theme', newTheme);
    
    showNotification(newTheme === 'dark' ? 'Dark mode enabled' : 'Light mode enabled', 'success');
}

// Load saved theme
function loadTheme() {
    const savedTheme = localStorage.getItem('theme') || 'light';
    document.documentElement.setAttribute('data-theme', savedTheme);
    
    const themeIcon = document.getElementById('theme-icon');
    if (themeIcon) {
        themeIcon.textContent = savedTheme === 'dark' ? '☀️' : '🌙';
    }
}

// ===== Language Management =====
function changeLanguage(lang) {
    currentLanguage = lang;
    updateLanguage();
    
    // Save language preference
    localStorage.setItem('language', lang);
    
    // Update active language button
    document.querySelectorAll('.lang-btn').forEach(btn => {
        btn.style.background = '';
        btn.style.color = '';
        btn.style.borderColor = '';
    });
    
    const activeBtn = document.querySelector(`[onclick="changeLanguage('${lang}')"]`);
    if (activeBtn) {
        activeBtn.style.background = 'var(--primary-color)';
        activeBtn.style.color = 'var(--text-light)';
        activeBtn.style.borderColor = 'var(--primary-color)';
    }
}

// Update all text elements with current language
function updateLanguage() {
    const langData = languages[currentLanguage];
    
    // Get all elements with id that matches language keys
    Object.keys(langData).forEach(key => {
        const element = document.getElementById(key);
        if (element) {
            element.textContent = langData[key];
        }
    });
    
    // Update placeholder attributes
    const placeholders = {
        uz: {
            'name': 'Ismingizni kiriting',
            'email': 'Email manzilingiz',
            'phone': 'Telefon raqamingiz',
            'message': 'Xabaringizni kiriting'
        },
        ru: {
            'name': 'Введите ваше имя',
            'email': 'Ваш email адрес',
            'phone': 'Ваш номер телефона',
            'message': 'Введите ваше сообщение'
        },
        en: {
            'name': 'Enter your name',
            'email': 'Enter your email',
            'phone': 'Enter your phone number',
            'message': 'Enter your message'
        }
    };
    
    const inputs = document.querySelectorAll('input, textarea');
    inputs.forEach(input => {
        const id = input.getAttribute('id');
        if (id && placeholders[currentLanguage] && placeholders[currentLanguage][id]) {
            input.placeholder = placeholders[currentLanguage][id];
        }
    });
}

// Load saved language
function loadLanguage() {
    const savedLang = localStorage.getItem('language') || 'uz';
    currentLanguage = savedLang;
    changeLanguage(savedLang);
}

// ===== Cart Management =====
let cart = [];

function addToCart(productId) {
    const product = {
        id: productId,
        title: document.getElementById(`product-${productId}-title`).textContent,
        price: document.getElementById(`product-${productId}-price`).textContent,
        image: `images/laptop-${productId}.png`
    };
    
    cart.push(product);
    updateCart();
    showNotification(getTranslation('added-to-cart'), 'success');
}

function removeFromCart(index) {
    cart.splice(index, 1);
    updateCart();
    showNotification(getTranslation('removed-from-cart'), 'success');
}

function updateCart() {
    const cartItemsContainer = document.getElementById('cart-items');
    const cartCount = document.getElementById('cart-count');
    const cartTotal = document.getElementById('cart-total-amount');
    
    if (cartItemsContainer) {
        cartItemsContainer.innerHTML = '';
        
        let total = 0;
        
        cart.forEach((item, index) => {
            const cartItem = document.createElement('div');
            cartItem.className = 'cart-item';
            
            const price = parseFloat(item.price.replace(/[^0-9.-]/g, ''));
            total += price;
            
            cartItem.innerHTML = `
                <img src="${item.image}" alt="${item.title}">
                <div class="cart-item-info">
                    <h4>${item.title}</h4>
                    <p>${item.price}</p>
                </div>
                <span class="cart-item-price">${item.price}</span>
                <button onclick="removeFromCart(${index})" class="remove-btn">✕</button>
            `;
            
            cartItemsContainer.appendChild(cartItem);
        });
        
        if (cartTotal) {
            cartTotal.textContent = formatCurrency(total);
        }
        
        if (cartCount) {
            cartCount.textContent = cart.length;
        }
    }
    
    // Save cart to localStorage
    localStorage.setItem('cart', JSON.stringify(cart));
}

function loadCart() {
    const savedCart = localStorage.getItem('cart');
    if (savedCart) {
        cart = JSON.parse(savedCart);
        updateCart();
    }
}

function openCart() {
    const modal = document.getElementById('cart-modal');
    if (modal) {
        modal.classList.add('active');
    }
}

function closeCart() {
    const modal = document.getElementById('cart-modal');
    if (modal) {
        modal.classList.remove('active');
    }
}

// Close modal when clicking outside
window.onclick = function(event) {
    const modal = document.getElementById('cart-modal');
    if (modal && event.target === modal) {
        closeCart();
    }
}

// ===== Form Handling =====
function handleFormSubmit(event) {
    event.preventDefault();
    
    const form = event.target;
    const formData = new FormData(form);
    const data = Object.fromEntries(formData);
    
    // Validate form
    if (!data.name || !data.email || !data.phone || !data.message) {
        showNotification('Please fill in all fields', 'error');
        return;
    }
    
    // Simulate form submission
    showNotification(getTranslation('form-submitted'), 'success');
    form.reset();
    
    // In a real application, you would send the data to a server here
    console.log('Form submitted:', data);
}

// ===== Notifications =====
function showNotification(message, type = 'success') {
    const notification = document.getElementById('notification');
    if (notification) {
        notification.textContent = message;
        notification.className = `notification ${type} show`;
        
        setTimeout(() => {
            notification.classList.remove('show');
        }, 3000);
    }
}

// Get translation based on current language
function getTranslation(key) {
    return languages[currentLanguage][key] || key;
}

// Format currency
function formatCurrency(amount) {
    return `$${amount.toFixed(2)}`;
}

// ===== Initialize =====
document.addEventListener('DOMContentLoaded', function() {
    // Load saved preferences
    loadTheme();
    loadLanguage();
    loadCart();
    
    // Add click handler to cart icon
    const cartIcon = document.querySelector('.cart-icon');
    if (cartIcon) {
        cartIcon.addEventListener('click', openCart);
    }
    
    // Add form submit handler
    const contactForm = document.querySelector('.contact-form');
    if (contactForm) {
        contactForm.addEventListener('submit', handleFormSubmit);
    }
    
    // Add smooth scroll for navigation links
    document.querySelectorAll('a[href^="#"]').forEach(anchor => {
        anchor.addEventListener('click', function(e) {
            e.preventDefault();
            const target = document.querySelector(this.getAttribute('href'));
            if (target) {
                target.scrollIntoView({
                    behavior: 'smooth',
                    block: 'start'
                });
            }
        });
    });
    
    // Add scroll effect to header
    let lastScroll = 0;
    const header = document.querySelector('.header');
    
    window.addEventListener('scroll', function() {
        const currentScroll = window.pageYOffset;
        
        if (header) {
            if (currentScroll > 100) {
                header.style.padding = '10px 0';
                header.style.boxShadow = '0 2px 20px rgba(0, 0, 0, 0.1)';
            } else {
                header.style.padding = '15px 0';
                header.style.boxShadow = 'none';
            }
        }
        
        lastScroll = currentScroll;
    });
    
    // Add animation on scroll
    const animateOnScroll = function() {
        const elements = document.querySelectorAll('.product-card, .about-content, .about-image, .stat-item');
        
        elements.forEach(element => {
            const elementPosition = element.getBoundingClientRect().top;
            const windowHeight = window.innerHeight;
            
            if (elementPosition < windowHeight - 100) {
                element.style.opacity = '1';
                element.style.transform = 'translateY(0)';
            }
        });
    };
    
    // Set initial styles for animation
    document.querySelectorAll('.product-card, .about-content, .about-image, .stat-item').forEach(element => {
        element.style.opacity = '0';
        element.style.transform = 'translateY(20px)';
        element.style.transition = 'opacity 0.6s ease, transform 0.6s ease';
    });
    
    window.addEventListener('scroll', animateOnScroll);
    window.addEventListener('load', animateOnScroll);
    
    // Initialize animations
    animateOnScroll();
});

